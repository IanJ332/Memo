class QualificationError(Exception):
    pass


def need(condition, code):
    if not condition:
        raise QualificationError(code)


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def safe_ancestors(path, *, private_leaf=False):
    """Reject symlinks and untrusted/writable ancestors before file creation."""
    path = Path(path)
    need(path.is_absolute() and path.resolve() == path, 'PATH_NOT_ABSOLUTE_CANONICAL')
    for node in (path, *path.parents):
        need(node.is_dir() and not node.is_symlink(), 'ANCESTOR_NOT_DIRECTORY')
        info = node.stat()
        need(info.st_uid in (0, os.geteuid()), 'ANCESTOR_OWNER')
        need(not stat.S_IMODE(info.st_mode) & 0o022, 'ANCESTOR_WRITABLE')
    if private_leaf:
        need(path.stat().st_uid == os.geteuid() and
             not stat.S_IMODE(path.stat().st_mode) & 0o077, 'PRIVATE_PARENT_REQUIRED')


def verify_record(distribution, prefix):
    """Verify installed RECORD hashes and sizes, with venv-contained paths."""
    prefix = Path(prefix).resolve()
    raw = distribution.read_text('RECORD')
    need(isinstance(raw, str), 'RECORD_MISSING')
    checked = 0
    unhashed_bytecode = 0
    seen = set()
    installed_files = {}
    for row in csv.reader(raw.splitlines()):
        need(len(row) == 3, 'RECORD_SHAPE')
        name, encoded, size = row
        path = Path(distribution.locate_file(name))
        need(not path.is_symlink() and path.resolve().is_relative_to(prefix), 'RECORD_ESCAPE')
        path = path.resolve()
        need(path not in seen and path.is_file(), 'RECORD_DUPLICATE_OR_MISSING')
        seen.add(path)
        body = path.read_bytes()
        # RECORD itself and generated bytecode are also bound prospectively,
        # although their wheel/installed RECORD has no content hash for them.
        installed_files[str(path)] = hashlib.sha256(body).hexdigest()
        if not encoded:
            need(not size, 'RECORD_UNHASHED_SIZE')
            if name.endswith('.dist-info/RECORD'):
                continue
            need(name.endswith('.pyc'), 'RECORD_UNHASHED_NON_BYTECODE')
            unhashed_bytecode += 1
            continue
        need(encoded.startswith('sha256='), 'RECORD_HASH_ALGORITHM')
        actual = base64.urlsafe_b64encode(hashlib.sha256(body).digest()).rstrip(b'=').decode()
        need(actual == encoded.partition('=')[2], 'RECORD_HASH_MISMATCH')
        need(size.isdecimal() and len(body) == int(size), 'RECORD_SIZE_MISMATCH')
        checked += 1
    return {'hashed_files_verified': checked, 'unhashed_bytecode_files': unhashed_bytecode,
            'installed_files': installed_files}


def selected_venv(root):
    """Select the explicit venv without executing site.main or package code.

    Python 3.12 leaves sys.prefix at the base installation with -S. The venv is
    therefore identified from the actually invoked executable and its config,
    while the process prefix remains separately and truthfully recorded.
    """
    root = Path(root)
    safe_ancestors(root, private_leaf=True)
    expected_prefix = root / '.venv'
    safe_ancestors(expected_prefix)
    safe_ancestors(expected_prefix / 'bin')
    need(Path(sys.executable).parent == expected_prefix / 'bin', 'EXECUTABLE_SELECTION')
    config_path = expected_prefix / 'pyvenv.cfg'
    need(config_path.is_file() and not config_path.is_symlink(), 'VENV_CONFIG_SELECTION')
    config = {}
    for line in config_path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        need('=' in line, 'VENV_CONFIG_SHAPE')
        key, value = (part.strip() for part in line.split('=', 1))
        need(key not in config, 'VENV_CONFIG_DUPLICATE')
        config[key] = value
    need(config.get('include-system-site-packages') == 'false', 'GLOBAL_SITE_ENABLED')
    need(config.get('version') == platform.python_version(), 'VENV_CONFIG_VERSION')
    need('executable' in config and
         Path(config['executable']).resolve() == Path(sys.executable).resolve(), 'VENV_CONFIG_EXECUTABLE')
    need(not any(name in sys.modules for name in ('sitecustomize', 'usercustomize')), 'SITE_HOOK_PRESENT')
    no_site = bool(sys.flags.no_site)
    if no_site:
        need(sys.prefix == sys.base_prefix, 'NO_SITE_PROCESS_PREFIX')
        need(site.ENABLE_USER_SITE in (None, False), 'USER_SITE_ENABLED')
        selected = expected_prefix / 'lib' / f'python{sys.version_info.major}.{sys.version_info.minor}' / 'site-packages'
        candidates = list((expected_prefix / 'lib').glob('python*/site-packages'))
        need(candidates == [selected] and selected.is_dir() and not selected.is_symlink(),
             'VENV_SITE_SELECTION')
        site_roots = [selected]
    else:
        need(Path(sys.prefix).resolve() == expected_prefix.resolve() and
             sys.prefix != sys.base_prefix, 'REPOSITORY_VENV_REQUIRED')
        need(site.ENABLE_USER_SITE is False, 'USER_SITE_ENABLED')
        site_roots = [Path(p) for p in site.getsitepackages()]
    need(site_roots and all(p.resolve().is_relative_to(expected_prefix.resolve()) for p in site_roots),
         'SITE_ROOT_ESCAPE')
    for directory in site_roots:
        safe_ancestors(directory)
        need(not list(directory.glob('*.pth')), 'PTH_PRESENT')
        need(not (directory / 'sitecustomize.py').exists() and
             not (directory / 'usercustomize.py').exists(), 'SITE_HOOK_PRESENT')
    for path in sys.path:
        if 'site-packages' in path or 'dist-packages' in path:
            need(not no_site, 'NO_SITE_PACKAGE_PATH')
            need(Path(path).resolve().is_relative_to(expected_prefix.resolve()), 'GLOBAL_SITE_PATH')
    return expected_prefix, site_roots, {
        'prefix': sys.prefix, 'process_prefix': sys.prefix, 'base_prefix': sys.base_prefix,
        'selected_venv_prefix': str(expected_prefix), 'no_site': no_site,
        'sys_path': list(sys.path), 'user_site': False, 'pth_files': 0,
        'selection': 'INVOKED_EXECUTABLE_AND_CONFIG' if no_site else 'ACTIVE_VENV_PREFIX',
        'site_main_executed_by_qualifier': False,
        'pyvenv_cfg': {'path': str(config_path), 'sha256': digest(config_path)}}


def native_identity(name, module):
    """Bind actual extension bytes or an actual interpreter-built-in module."""
    spec = getattr(module, '__spec__', None)
    origin = getattr(spec, 'origin', None)
    need(getattr(module, '__name__', None) == name and getattr(spec, 'name', None) == name,
         'NATIVE_MODULE_NAME')
    if origin == 'built-in':
        need(name in sys.builtin_module_names and
             getattr(spec, 'loader', None) is importlib.machinery.BuiltinImporter,
             'NATIVE_BUILTIN_IDENTITY')
        executable = Path(sys.executable).resolve()
        return {'kind': 'BUILTIN', 'module': name,
                'interpreter_realpath': str(executable), 'interpreter_sha256': digest(executable)}
    filename = getattr(module, '__file__', None)
    need(isinstance(origin, str) and isinstance(filename, str) and
         origin not in ('built-in', 'frozen'), 'NATIVE_MODULE_ORIGIN')
    path = Path(filename)
    need(path.is_absolute() and path.is_file() and not path.is_symlink() and
         Path(origin).resolve() == path.resolve() and
         any(str(path).endswith(suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES),
         'NATIVE_EXTENSION_SELECTION')
    path = path.resolve()
    return {'kind': 'EXTENSION', 'module': name, 'path': str(path), 'sha256': digest(path)}


def runtime_metadata(root):
    root = Path(root)
    need(sys.platform == 'linux', 'LINUX_REQUIRED')
    need(sys.flags.isolated and sys.dont_write_bytecode, 'ISOLATED_NO_BYTECODE_REQUIRED')
    expected_prefix, site_roots, isolation = selected_venv(root)
    distributions = []
    records = {}
    installed_files = {}
    for distribution in importlib.metadata.distributions(path=[str(p) for p in site_roots]):
        name, version = distribution.metadata['Name'], distribution.version
        key = name.casefold().replace('_', '-')
        need(key not in records, 'DUPLICATE_DISTRIBUTION')
        verification = verify_record(distribution, expected_prefix)
        files = verification.pop('installed_files')
        need(not installed_files.keys() & files.keys(), 'DISTRIBUTION_FILE_OWNERSHIP_OVERLAP')
        installed_files.update(files)
        records[key] = verification
        metadata = {}
        for filename in ('METADATA', 'RECORD', 'WHEEL'):
            value = distribution.read_text(filename)
            if value is not None:
                metadata[filename] = hashlib.sha256(value.encode()).hexdigest()
        distributions.append({'name': name, 'version': version, 'metadata_sha256': metadata})
    for directory in site_roots:
        for path in directory.rglob('*'):
            need(not path.is_symlink(), 'SITE_TREE_SYMLINK')
            if path.is_file():
                need(str(path.resolve()) in installed_files, 'UNRECORDED_SITE_FILE')
    import _ssl
    import _sqlite3
    native = {}
    for name, module in (('_ssl', _ssl), ('_sqlite3', _sqlite3), ('fcntl', fcntl)):
        native[name] = native_identity(name, module)
    shared_libraries = {}
    for line in Path('/proc/self/maps').read_text().splitlines():
        fields = line.split(maxsplit=5)
        if len(fields) != 6 or not fields[5].startswith('/'):
            continue
        filename = fields[5]
        if '.so' not in filename:
            continue
        need(not filename.endswith(' (deleted)'), 'DELETED_MAPPED_LIBRARY')
        path = Path(filename).resolve()
        need(path.is_file(), 'MAPPED_LIBRARY_MISSING')
        shared_libraries[str(path)] = digest(path)
    paths = ssl.get_default_verify_paths()
    need(paths.cafile is not None and Path(paths.cafile).is_file(), 'DEFAULT_CA_FILE_MISSING')
    context = ssl.create_default_context()
    need(context.check_hostname and context.verify_mode == ssl.CERT_REQUIRED and
         context.cert_store_stats()['x509_ca'] > 0, 'TLS_TRUST_INVALID')
    trust = {'cafile': str(Path(paths.cafile).resolve()), 'cafile_sha256': digest(paths.cafile),
             'certificate_statistics': context.cert_store_stats(), 'hostname_validation': True,
             'certificate_verification': 'CERT_REQUIRED', 'network_test': 'NOT_PERFORMED'}
    return {'python': {'executable': sys.executable, 'realpath': str(Path(sys.executable).resolve()),
                'sha256': digest(Path(sys.executable).resolve()), 'version': sys.version,
                'platform': platform.platform(), 'sqlite': sqlite3.sqlite_version},
            'distributions': sorted(distributions, key=lambda item: item['name'].casefold()),
            'installed_record_verification': records, 'native_modules': native,
            'installed_files': dict(sorted(installed_files.items())),
            'mapped_shared_libraries': dict(sorted(shared_libraries.items())),
            'openssl': ssl.OPENSSL_VERSION, 'trust': trust,
            'isolation': isolation}


def child(code, *args):
    return subprocess.run([sys.executable, '-I', '-S', '-B', '-c', code, *map(str, args)],
                          capture_output=True, timeout=10, check=False)


def storage_probes(directory):
    """Test logical recovery and process exclusion, never power-loss durability."""
    directory = Path(directory)
    need(directory.is_absolute() and not directory.exists() and not directory.is_symlink(),
         'PROBE_DIRECTORY_MUST_BE_FRESH')
    old_umask = os.umask(0o077)
    try:
        directory.mkdir(mode=0o700)
        path = directory / 'qualification-only.sqlite'
        db = sqlite3.connect(path, timeout=.1)
        db.execute('PRAGMA synchronous=FULL')
        db.execute('create table reservations(protocol text primary key)')
        db.commit()
        db.execute('begin immediate')
        db.execute("insert into reservations values('disposable-only')")
        db.rollback()
        need(db.execute('select count(*) from reservations').fetchone() == (0,), 'ROLLBACK_FAILED')
        db.execute('begin immediate')
        result = child("""import sqlite3,sys
b=sqlite3.connect(sys.argv[1],timeout=.1)
try:b.execute('begin immediate')
except sqlite3.OperationalError as e:
 sys.exit(0 if 'locked' in str(e) else 2)
sys.exit(1)
""", path)
        need(result.returncode == 0, 'SQLITE_CROSS_PROCESS_LOCK_FAILED')
        db.execute("insert into reservations values('disposable-only')")
        db.commit()
        db.close()
        db = sqlite3.connect(path, timeout=.1)
        need(db.execute('select * from reservations').fetchall() == [('disposable-only',)], 'COMMIT_REOPEN_FAILED')
        try:
            db.execute("insert into reservations values('disposable-only')")
        except sqlite3.IntegrityError:
            db.rollback()
        else:
            raise QualificationError('UNIQUE_RESERVATION_FAILED')
        need(db.execute('pragma integrity_check').fetchone() == ('ok',), 'SQLITE_INTEGRITY')
        need(db.execute('pragma journal_mode=WAL').fetchone()[0] == 'wal', 'WAL_UNAVAILABLE')
        db.execute("insert into reservations values('wal-disposable')")
        db.commit()
        # Inspect live sidecars before normal SQLite closure may remove them.
        for candidate in directory.iterdir():
            need(candidate.stat().st_uid == os.geteuid() and
                 not stat.S_IMODE(candidate.stat().st_mode) & 0o077, 'PRIVATE_SIDECAR_FAILED')
        db.close()
        lockpath = directory / 'qualification-only.lock'
        with lockpath.open('xb') as stream:
            fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            result = child("""import fcntl,sys
with open(sys.argv[1],'rb') as f:
 try:fcntl.flock(f,fcntl.LOCK_EX|fcntl.LOCK_NB)
 except BlockingIOError:sys.exit(0)
sys.exit(1)
""", lockpath)
            need(result.returncode == 0, 'FCNTL_CROSS_PROCESS_LOCK_FAILED')
        recovery = directory / 'interruption-only.sqlite'
        code = """import sqlite3,sys,time
d=sqlite3.connect(sys.argv[1]);d.execute('pragma journal_mode=WAL');d.execute('pragma synchronous=FULL')
d.execute('create table t(k integer primary key)');d.commit()
d.execute('insert into t values(1)');d.commit()
d.execute('begin immediate');d.execute('insert into t values(2)')
print('COMMITTED_ONE_UNCOMMITTED_TWO',flush=True)
time.sleep(30)
"""
        process = subprocess.Popen([sys.executable, '-I', '-S', '-B', '-c', code, str(recovery)],
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        try:
            ready, _, _ = select.select([process.stdout], [], [], 5)
            need(bool(ready) and process.stdout.readline() == b'COMMITTED_ONE_UNCOMMITTED_TWO\n', 'RECOVERY_CHILD_NOT_READY')
            process.kill()
            process.wait(timeout=5)
        finally:
            if process.poll() is None:
                process.kill(); process.wait(timeout=5)
            process.stdout.close(); process.stderr.close()
        with sqlite3.connect(recovery) as check:
            need(check.execute('select * from t').fetchall() == [(1,)], 'INTERRUPTED_RECOVERY_FAILED')
            need(check.execute('pragma integrity_check').fetchone() == ('ok',), 'RECOVERY_INTEGRITY')
        for candidate in directory.iterdir():
            need(candidate.is_file() and not candidate.is_symlink() and
                 candidate.stat().st_uid == os.geteuid() and
                 not stat.S_IMODE(candidate.stat().st_mode) & 0o077, 'PRIVATE_STORAGE_FAILED')
        fd = os.open(directory, os.O_RDONLY)
        try: os.fsync(fd)
        finally: os.close(fd)
        return {'rollback': 'PASS', 'sqlite_cross_process_lock': 'PASS', 'unique_key': 'PASS',
                'commit_reopen': 'PASS', 'integrity': 'PASS', 'WAL': 'PASS',
                'fcntl_cross_process_lock': 'PASS', 'killed_process_recovery': 'PASS',
                'private_storage_and_sidecars': 'PASS', 'power_loss_durability': 'NOT_TESTED',
                'scientific_attempts_consumed': 0}
    finally:
        os.umask(old_umask)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['qualify'])
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--probe-dir', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args(argv)
    root = args.root
    need(root.is_absolute() and root.resolve() == root, 'ROOT_SELECTION')
    need(args.probe_dir.parent.resolve() == root.parent.resolve(), 'PROBE_PARENT_SELECTION')
    need(args.output.parent.resolve() == root.parent.resolve(), 'OUTPUT_PARENT_SELECTION')
    need(not args.output.exists() and not args.output.is_symlink(), 'OUTPUT_EXISTS')
    safe_ancestors(root.parent, private_leaf=True)
    result = runtime_metadata(root)
    result.update(format='phase2b5-linux-runtime-v3', root=str(root),
                  measured_utc=time.time(), authority='OBSERVATIONS_ONLY_NO_APPROVAL',
                  storage=storage_probes(args.probe_dir))
    raw = (json.dumps(result, sort_keys=True, indent=2) + '\n').encode()
    fd = os.open(args.output, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(raw); stream.flush(); os.fsync(stream.fileno())
    print(json.dumps({'status': 'OFFLINE_QUALIFICATION_PASS', 'output_sha256': hashlib.sha256(raw).hexdigest(),
                      'scientific_attempts_consumed': 0}))
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except QualificationError as error:
        print(json.dumps({'status': 'QUALIFICATION_FAILED', 'code': str(error)}))
        raise SystemExit(1)
